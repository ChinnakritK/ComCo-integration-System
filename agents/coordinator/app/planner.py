"""Planning: turn a natural-language request into an ordered list of tool calls.

Two interchangeable planners produce the same `Plan`:

* RulePlanner (default) - deterministic intent + entity extraction. Always
  available, fully explainable, no model needed to evaluate the solution.
* LlmPlanner (optional, USE_LLM=true) - asks a local Ollama model to choose
  tools. Its output is *validated* (known tools, valid argument formats, and
  every ID must literally appear in the user's request - the model cannot
  invent an ID). Any failure falls back to the RulePlanner.

The planner only decides WHAT to call. Answers are composed exclusively from
tool results (see answer.py), so business data is never generated by a model.
"""

from __future__ import annotations

import json
import re
from dataclasses import asdict, dataclass, field

import httpx

from comco_agentkit import TOOLS, tool_catalog
from comco_common import get_logger

log = get_logger(__name__)

CUSTOMER_RE = re.compile(r"\b(c\d{3,})\b", re.IGNORECASE)
ORDER_RE = re.compile(r"\b(o\d{4,})\b", re.IGNORECASE)
LATEST_RE = re.compile(r"\b(latest|last|most recent|recent|newest|current)\b[\w\s]{0,20}\border", re.IGNORECASE)
ORDER_LIST_RE = re.compile(r"\b(orders|order history|all (?:of )?(?:their|his|her) orders|purchases)\b", re.IGNORECASE)
DOMAIN_RE = re.compile(r"\b(customer|client|order|orders|status|purchase)\b", re.IGNORECASE)

MAX_ENTITIES = 3


@dataclass
class PlannedStep:
    id: str
    tool: str
    args: dict
    reason: str
    depends_on: list[str] = field(default_factory=list)


@dataclass
class Plan:
    intent: str
    steps: list[PlannedStep]
    planner: str
    message: str | None = None  # clarification / unsupported explanation

    def to_dict(self) -> dict:
        return asdict(self)


# ------------------------------------------------------------------ rule-based
class RulePlanner:
    name = "rules"

    async def plan(self, query: str) -> Plan:
        return build_rule_plan(query)


def build_rule_plan(query: str) -> Plan:
    customers = _unique(m.upper() for m in CUSTOMER_RE.findall(query))[:MAX_ENTITIES]
    orders = _unique(m.upper() for m in ORDER_RE.findall(query))[:MAX_ENTITIES]
    wants_latest = bool(LATEST_RE.search(query))
    wants_order_list = bool(ORDER_LIST_RE.search(query)) and not wants_latest

    steps: list[PlannedStep] = []
    for oid in orders:
        steps.append(PlannedStep(f"order_{oid}", "get_order", {"order_id": oid}, f"Order ID {oid} mentioned"))

    for cid in customers:
        cstep = f"customer_{cid}"
        steps.append(
            PlannedStep(cstep, "get_customer", {"customer_id": cid},
                        f"Customer ID {cid} mentioned - fetch profile and confirm the customer exists")
        )
        if wants_latest:
            steps.append(
                PlannedStep(f"latest_order_{cid}", "get_latest_order", {"customer_id": cid},
                            "Request asks for the latest/most recent order", depends_on=[cstep])
            )
        elif wants_order_list:
            steps.append(
                PlannedStep(f"orders_{cid}", "list_customer_orders", {"customer_id": cid},
                            "Request asks for the customer's orders", depends_on=[cstep])
            )

    if steps:
        return Plan(_intent(customers, orders, wants_latest, wants_order_list), steps, "rules")

    if DOMAIN_RE.search(query):
        return Plan(
            "needs_clarification", [], "rules",
            "Please include a customer ID (e.g. C001) or an order ID (e.g. O1001) so I can look it up.",
        )
    return Plan(
        "unsupported", [], "rules",
        "I can answer questions about customers and their orders, e.g. 'Show customer C001', "
        "'Show customer C001 and their latest order' or 'What is the status of order O1001?'.",
    )


def _intent(customers, orders, latest, order_list) -> str:
    parts = []
    if customers:
        parts.append("customer_profile")
        if latest:
            parts.append("latest_order")
        elif order_list:
            parts.append("order_history")
    if orders:
        parts.append("order_lookup")
    return "+".join(parts)


def _unique(items) -> list[str]:
    seen: dict[str, None] = {}
    for i in items:
        seen.setdefault(i, None)
    return list(seen)


# ------------------------------------------------------------------ LLM (optional)
_SYSTEM_PROMPT = """You are the planning component of a customer-service agent.
Choose which tools to call to answer the user's request. You do NOT answer the question.
Available tools (JSON): {tools}
Rules:
- Only use tools from the list, with arguments exactly matching the patterns.
- Only use customer IDs (like C001) and order IDs (like O1001) that appear in the user's request.
- If the request mentions a customer ID, call get_customer for it first.
- Use get_latest_order for "latest/last/most recent order" questions.
- If nothing applies, return an empty list.
Respond ONLY with JSON: {{"steps": [{{"tool": "<name>", "args": {{...}}, "reason": "<short>"}}]}}"""


class LlmPlanner:
    def __init__(self, base_url: str, model: str, timeout_seconds: float, transport=None) -> None:
        self.model = model
        self.name = f"llm:{model}"
        self._client = httpx.AsyncClient(base_url=base_url, timeout=timeout_seconds, transport=transport)

    async def aclose(self) -> None:
        await self._client.aclose()

    async def plan(self, query: str) -> Plan:
        try:
            raw = await self._ask(query)
            plan = self._validate(query, raw)
            log.info("llm_plan_accepted", model=self.model, steps=len(plan.steps))
            return plan
        except Exception as exc:  # noqa: BLE001 - any LLM problem -> deterministic fallback
            reason = f"{type(exc).__name__}: {str(exc)[:120]}"
            log.warning("llm_plan_rejected", model=self.model, reason=reason)
            fallback = build_rule_plan(query)
            fallback.planner = f"rules (fallback from {self.name}: {reason})"
            return fallback

    async def _ask(self, query: str) -> dict:
        response = await self._client.post(
            "/api/chat",
            json={
                "model": self.model,
                "stream": False,
                "format": "json",
                "options": {"temperature": 0},
                "messages": [
                    {"role": "system", "content": _SYSTEM_PROMPT.format(tools=json.dumps(tool_catalog()))},
                    {"role": "user", "content": query},
                ],
            },
        )
        response.raise_for_status()
        return json.loads(response.json()["message"]["content"])

    def _validate(self, query: str, raw: dict) -> Plan:
        mentioned = {m.upper() for m in CUSTOMER_RE.findall(query)} | {m.upper() for m in ORDER_RE.findall(query)}
        steps: list[PlannedStep] = []
        customer_steps: dict[str, str] = {}
        for i, item in enumerate(raw.get("steps", [])[: MAX_ENTITIES * 2]):
            tool, args = item.get("tool"), {k: str(v).upper() for k, v in (item.get("args") or {}).items()}
            if tool not in TOOLS:
                raise ValueError(f"unknown tool {tool!r}")
            problem = TOOLS[tool].validate(args)
            if problem:
                raise ValueError(problem)
            invented = set(args.values()) - mentioned
            if invented:
                raise ValueError(f"model used IDs not present in the request: {sorted(invented)}")
            step = PlannedStep(f"s{i + 1}_{tool}", tool, args, str(item.get("reason") or "selected by LLM")[:200])
            if tool == "get_customer":
                customer_steps[args["customer_id"]] = step.id
            steps.append(step)
        # Enforce the same safety ordering as the rule planner: confirm the customer first.
        for step in steps:
            cid = step.args.get("customer_id")
            if step.tool != "get_customer" and cid in customer_steps:
                step.depends_on = [customer_steps[cid]]
        if not steps:
            fallback = build_rule_plan(query)
            fallback.planner = f"rules ({self.name} selected no tools)"
            return fallback
        intent = "+".join(sorted({s.tool for s in steps}))
        return Plan(intent, steps, self.name)
